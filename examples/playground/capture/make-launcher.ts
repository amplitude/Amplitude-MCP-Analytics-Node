import { chmod, mkdir, writeFile } from 'node:fs/promises';
import { join } from 'node:path';
import { fileURLToPath } from 'node:url';
import { parseArgs, requiredArg } from './context.js';

/**
 * Write a self-contained `launch-stdio.sh` into a trial directory.
 *
 * Desktop apps (Claude Desktop, Cursor) spawn MCP servers with a minimal
 * environment — no shell PATH, no pnpm, no AMPLITUDE_* variables — so the
 * script pins the absolute node binary and repo path, unsets the API key, and
 * `exec`s the capture stdio entry directly.
 */
const REPO_ROOT = fileURLToPath(new URL('../../..', import.meta.url));

const args = parseArgs(process.argv.slice(2));
const outDir = requiredArg(args, 'out');
const trial = requiredArg(args, 'trial');
const mode = args.get('mode') ?? 'stdio';
if (mode !== 'stdio') {
  process.stderr.write(`[capture] make-launcher only supports --mode stdio (got ${mode})\n`);
  process.exit(2);
}

const extraFlags = (['client-product', 'client-surface', 'client-version', 'topology'] as const)
  .map((name) => {
    const value = args.get(name);
    return value === undefined ? '' : ` --${name} ${shellQuote(value)}`;
  })
  .join('');

const script = `#!/bin/sh
# Generated by examples/playground/capture/make-launcher.ts — captures one
# MCP-over-stdio session into the trial directory, sanitized.
cd ${shellQuote(REPO_ROOT)} || exit 1
unset AMPLITUDE_API_KEY
exec ${shellQuote(process.execPath)} --disable-warning=ExperimentalWarning --experimental-strip-types \\
  --import ${shellQuote(join(REPO_ROOT, 'examples/playground/register-ts.mjs'))} \\
  ${shellQuote(join(REPO_ROOT, 'examples/playground/capture/stdio.ts'))} \\
  --trial ${shellQuote(trial)} --out ${shellQuote(outDir)}${extraFlags}
`;

await mkdir(outDir, { recursive: true });
const path = join(outDir, 'launch-stdio.sh');
await writeFile(path, script, 'utf8');
await chmod(path, 0o755);
process.stderr.write(`[capture] wrote ${path}\n`);

function shellQuote(value: string): string {
  return `'${value.replace(/'/g, `'\\''`)}'`;
}
